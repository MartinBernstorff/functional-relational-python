def compile_catalog(
    views: Sequence[View],
    payloads: Sequence[Payload],
    unions: Sequence[Union] = (),
) -> compiler.CompiledCatalog:
    return compiler.compile_catalog(
        EntityGraph.build([Company], IdBase.fake(), OneToOneMarker.fake()).unwrap(),
        views,
        payloads,
        unions,
    ).unwrap()


def view(source: type[pydantic.BaseModel]) -> View:
    return View(
        name=ViewName(f"{source.__name__}View"), source=source, step=steps.pipeline()
    )


def single_module(module: ModulePath) -> ModuleLayout:
    return lambda _: module


def generate(
    views: Sequence[View],
    payloads: Sequence[Payload],
    layout: ModuleLayout,
    unions: Sequence[Union] = (),
) -> GeneratedFiles:
    match PythonPlan.of(
        compile_catalog(views, payloads, unions),
        PythonLayout.models_only(layout),
    ):
        case Ok(plan):
            return PythonRenderer.render(plan)
        case Err(error):
            pytest.fail(f"expected generated files, got {error}")


