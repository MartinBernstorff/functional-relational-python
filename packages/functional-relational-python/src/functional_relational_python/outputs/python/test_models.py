def test_generated_modules_pass_the_type_checker(tmp_path: Path) -> None:
    files = generate(
        [
            View(
                name=ViewName("CompanySummary"),
                source=Company,
                step=steps.omit(FieldName("secret")),
            ),
            View(name=ViewName("WithInner"), source=Outer, step=steps.pipeline()),
            *hydrated_views(),
            defaulted_settings(),
        ],
        [],
        single_module(ModulePath("generated.views")),
    )
    files.write(LocalFileSystem(), Directory(tmp_path)).unwrap()
    source_root = Path(__file__).parents[2]
    _ = (tmp_path / "pyrefly.toml").write_text(
        f'search-path = ["{tmp_path}", "{source_root}"]\n'
        f'python-interpreter-path = "{sys.executable}"\n'
        'preset = "all"\n',
        encoding="utf-8",
    )

    result = subprocess.run(
        [sys.executable, "-m", "pyrefly", "check", "--config", "pyrefly.toml"],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )

    assert result.returncode == 0, result.stdout + result.stderr
