        ("created_at", datetime.datetime(3000, 1, 1, tzinfo=datetime.UTC)),
        ("deleted_at", datetime.datetime(3000, 1, 1, tzinfo=datetime.UTC)),
        ("budget", 0),
        ("ratio", 2.0),
