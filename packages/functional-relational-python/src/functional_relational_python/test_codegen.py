class Text(pydantic.RootModel[str], frozen=True):
    pass


class CompanyId(Id[int]):
    pass


class Company(pydantic.BaseModel):
    id: CompanyId
    name: Text
    parent: CompanyId | None
    tags: tuple[Text, ...]
    kind: Literal["shop", "brand"]
    secret: Text


class Outer(pydantic.BaseModel):
    class Inner(pydantic.RootModel[str], frozen=True):
        pass

    inner: Inner


def compile_views(views: list[View]) -> compiler.CompiledViews:
    return compiler.compile_views(EntityGraph.build([Company]).unwrap(), views).unwrap()


def view(source: type[pydantic.BaseModel]) -> View:
    return View(
        name=ViewName(f"{source.__name__}View"), source=source, step=steps.pipeline()
    )


def single_module(module: ModulePath) -> ModuleLayout:
    return lambda _: module


def generate(views: list[View], layout: ModuleLayout | None = None) -> GeneratedFiles:
    match Codegen.generate(
        compile_views(views), layout or single_module(ModulePath.fake())
    ):
        case Ok(files):
            return files
        case Err(error):
            pytest.fail(f"expected generated files, got {error}")


def diagnostics_of(
    views: list[View], layout: ModuleLayout | None = None
) -> tuple[Diagnostic, ...]:
    match Codegen.generate(
        compile_views(views), layout or single_module(ModulePath.fake())
    ):
        case Ok(files):
            pytest.fail(f"expected diagnostics, got {files}")
        case Err(error):
            return error.diagnostics


def test_golden_view_model() -> None:
    files = generate(
        [
            View(
                name=ViewName("CompanySummary"),
                source=Company,
                step=steps.omit(FieldName("secret")),
            )
        ],
        single_module(ModulePath("app.views.company")),
    )

    assert [str(file.path.root) for file in files.files] == ["app/views/company.py"]
    assert files.files[0].text == FileText(
        """\
# Generated by functional-relational-python. Do not edit.
# Regenerate with `frp generate`; `frp check` fails when this is stale.

from typing import Literal

from functional_relational_python.test_codegen import CompanyId, Text
from pydantic import BaseModel


class CompanySummary(BaseModel, frozen=True):
    id: CompanyId
    name: Text
    parent: CompanyId | None
    tags: tuple[Text, ...]
    kind: Literal['shop', 'brand']
"""
    )


def hydrated_views() -> list[View]:
    """A Reference resolved to the Entity itself, and one through a nested pipeline."""
    parent = steps.select(lambda field: field.name == FieldName("parent"))
    return [
        View(
            name=ViewName("CompanyWithParent"),
            source=Company,
            step=steps.pipeline(
                steps.project([FieldName("id"), FieldName("parent")]),
                steps.hydrate(),
            ),
        ),
        View(
            name=ViewName("CompanyTree"),
            source=Company,
            step=steps.pipeline(
                steps.project([FieldName("id"), FieldName("parent")]),
                steps.resolve(parent, steps.project([FieldName("name")])),
            ),
        ),
    ]


def test_golden_hydrated_view_models() -> None:
    files = generate(hydrated_views())

    assert files.files[0].text == FileText(
        """\
# Generated by functional-relational-python. Do not edit.
# Regenerate with `frp generate`; `frp check` fails when this is stale.

from functional_relational_python.test_codegen import Company, CompanyId, Text
from pydantic import BaseModel


class CompanyWithParent(BaseModel, frozen=True):
    id: CompanyId
    parent: Company | None


class CompanyTreeParent(BaseModel, frozen=True):
    name: Text


class CompanyTree(BaseModel, frozen=True):
    id: CompanyId
    parent: CompanyTreeParent | None
"""
    )


def test_golden_nested_class_and_empty_model() -> None:
    omit_inner = steps.omit(FieldName("inner"))
    files = generate(
        [
            View(name=ViewName("WithInner"), source=Outer, step=steps.pipeline()),
            View(name=ViewName("Empty"), source=Outer, step=omit_inner),
        ]
    )

    assert files.files[0].text == FileText(
        """\
# Generated by functional-relational-python. Do not edit.
# Regenerate with `frp generate`; `frp check` fails when this is stale.

from functional_relational_python.test_codegen import Outer
from pydantic import BaseModel


class WithInner(BaseModel, frozen=True):
    inner: Outer.Inner


class Empty(BaseModel, frozen=True):
    pass
"""
    )


def test_each_module_is_one_file_in_module_order() -> None:
    company, outer = view(Company), view(Outer)
    modules = {
        company.name: ModulePath("app.z_last"),
        outer.name: ModulePath("app.a_first"),
    }

    files = generate([company, outer], lambda compiled: modules[compiled.name])

    assert [file.path.root for file in files.files] == [
        modules[outer.name].file_path().root,
        modules[company.name].file_path().root,
    ]


class ATypeWithAVeryLongNameSoThatImportsWrap(pydantic.RootModel[str], frozen=True):
    pass


class ManyImports(pydantic.BaseModel):
    long: ATypeWithAVeryLongNameSoThatImportsWrap
    id: CompanyId
    text: Text


def test_an_import_longer_than_a_line_is_wrapped() -> None:
    text = generate([view(ManyImports)]).files[0].text.root

    assert (
        """\
from functional_relational_python.test_codegen import (
    ATypeWithAVeryLongNameSoThatImportsWrap,
    CompanyId,
    Text,
)
"""
        in text
    )


def local_source() -> type[pydantic.BaseModel]:
    class LocalText(pydantic.RootModel[str]):
        pass

    class WithLocal(pydantic.BaseModel):
        text: LocalText

    return WithLocal


class WithUnsupported(pydantic.BaseModel):
    nested_annotated: tuple[Annotated[Text, "metadata"], ...]
    callable: Callable[[Text], Text]


def test_unimportable_type_is_a_diagnostic() -> None:
    source = local_source()

    assert diagnostics_of([view(source)]) == (
        UnimportableType.model_validate(
            {
                "view": view(source).name,
                "field": FieldName("text"),
                "annotation": repr(source.model_fields["text"].annotation),
            }
        ),
    )


def test_every_unsupported_annotation_is_reported() -> None:
    reported = diagnostics_of([view(WithUnsupported)])

    assert [
        (type(diagnostic), diagnostic.field)
        for diagnostic in reported
        if isinstance(diagnostic, UnsupportedAnnotation)
    ] == [
        (UnsupportedAnnotation, FieldName(name))
        for name in WithUnsupported.model_fields
    ]


def test_invalid_view_name_is_a_diagnostic() -> None:
    name = ViewName("not a class")

    assert diagnostics_of([View(name=name, source=Company, step=steps.pipeline())]) == (
        InvalidModelName(view=name),
    )


def test_same_name_in_one_module_is_a_diagnostic() -> None:
    first, second = view(Company), view(Outer)
    name = ViewName("Same")
    module = ModulePath.fake()

    assert diagnostics_of(
        [
            first.model_copy(update={"name": name}),
            second.model_copy(update={"name": name}),
        ],
        single_module(module),
    ) == (
        DuplicateModelName(
            module=module, name=Identifier(name.root), views=(name, name)
        ),
    )


def test_same_name_in_different_modules_is_allowed() -> None:
    name = ViewName("Same")
    views = [
        view(Company).model_copy(update={"name": name}),
        view(Outer).model_copy(update={"name": name}),
    ]
    modules = iter([ModulePath("app.one"), ModulePath("app.two")])

    assert len(generate(views, lambda _: next(modules)).files) == len(views)


def test_model_named_like_an_imported_type_is_a_clash() -> None:
    clashing = View(name=ViewName(Text.__name__), source=Company, step=steps.pipeline())
    module = ModulePath.fake()

    assert diagnostics_of([clashing], single_module(module)) == (
        NameClash.model_validate(
            {
                "module": module,
                "name": Text.__name__,
                "origins": (
                    f"{module.root}.{Text.__name__}",
                    f"{Text.__module__}.{Text.__name__}",
                ),
            }
        ),
    )


def test_generated_modules_pass_the_type_checker(tmp_path: Path) -> None:
    files = generate(
        [
            View(
                name=ViewName("CompanySummary"),
                source=Company,
                step=steps.omit(FieldName("secret")),
            ),
            View(name=ViewName("WithInner"), source=Outer, step=steps.pipeline()),
            *hydrated_views(),
        ],
        single_module(ModulePath("generated.views")),
    )
    files.write(LocalFileSystem(), Directory(tmp_path))
    source_root = Path(__file__).parent.parent
    _ = (tmp_path / "pyrefly.toml").write_text(
        f'search-path = ["{tmp_path}", "{source_root}"]\n'
        f'python-interpreter-path = "{sys.executable}"\n'
        'preset = "all"\n',
        encoding="utf-8",
    )

    result = subprocess.run(
        [sys.executable, "-m", "pyrefly", "check", "--config", "pyrefly.toml"],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )

    assert result.returncode == 0, result.stdout + result.stderr
